_SUMMARY_TMPL = {
    "foundational": "「{n}」的基本定义与核心要点，是本课程后续内容的基础",
    "core": "「{n}」的关键性质、典型方法与常见易错点",
    "advanced": "「{n}」的综合应用、性能权衡与实际工程场景",
}
_WEIGHTS = (0.9, 0.85, 0.8, 0.75, 0.7, 0.65)


def _rows(code: str) -> list[tuple]:
    """种子表 → 概念行：cid 顺序编号，先修沿学习路径成链，tier/权重按位置生成。"""
    rows: list[tuple] = []
    i = 0
    for chap, names in _SEEDS[code]:
        for n in names:
            tier = "foundational" if i < 10 else ("core" if i < 23 else "advanced")
            prereqs = [f"{code}_c{i - 1:02d}"] if i else []
            rows.append((f"{code}_c{i:02d}", n, chap,
                         _SUMMARY_TMPL[tier].format(n=n),
                         prereqs, _WEIGHTS[i % len(_WEIGHTS)], tier))
            i += 1
    return rows


COURSE_ROWS_EXT: dict[str, list[tuple]] = {code: _rows(code) for code in COURSES_EXT}

