"""快速排序实现与测试用例。

这个文件同时包含两部分内容：
1. 快速排序算法的实现
2. 10 个覆盖不同场景的测试用例

如果直接运行这个文件（python scholarpulse/core/c.py），
程序会自动执行测试并输出每一条测试的结果。
"""

# from __future__ import annotations
# 这行用于启用 Python 3.7+ 的未来特性注解语法，
# 让我们可以在类型注解里直接使用 | 这种联合类型写法，
# 例如 list[int | float]，这样代码更现代也更易读。
from __future__ import annotations


# 定义一个函数 quick_sort，用于对输入列表进行快速排序。
# 参数 nums 是一个列表，元素类型可以是 int 或 float。
# 返回值是一个新的已排序列表，不会直接修改原始输入。
def quick_sort(nums: list[int | float]) -> list[int | float]:
    """返回一个新列表，对输入进行快速排序。

    快速排序的核心思想是：
    - 选一个基准值（pivot）
    - 把小于等于 pivot 的数放左边
    - 把大于 pivot 的数放右边
    - 对左右两边再递归执行同样的操作

    这样可以把一个大问题拆成多个更小的问题，直到每个部分都变成很小、
    很容易处理的情况，最终得到整体有序结果。
    """
    # 复制一份输入列表，避免直接修改调用者传入的数组。
    # 这样函数对外部数据具有更好的“非破坏性”特性。
    arr = list(nums)

    # 如果数组长度小于等于 1，说明它已经有序，直接返回。
    # 这样可以避免无意义的递归调用。
    if len(arr) <= 1:
        return arr

    # 定义一个内部递归函数，用来处理指定区间的快速排序。
    # left 表示区间左边界，right 表示区间右边界。
    def _quick_sort(left: int, right: int) -> None:
        """内部递归函数：对 arr[left:right+1] 进行原地快速排序。"""
        # 当区间长度为 0 或 1 时，不需要继续排序，直接返回。
        # 例如 left == right，说明只有一个元素；
        # left > right，说明区间为空。
        if left >= right:
            return

        # 以当前区间最右边的元素作为基准值（pivot）。
        # 这是快速排序里最常见的做法之一：
        # 把右端点当作一个“参考值”，然后把比它小的元素放到左边，
        # 比它大的元素放到右边。这样可以把结果逐步分成左右两部分。
        pivot = arr[right]

        # i 表示当前已经确定好的“左侧区间”的最后一个位置。
        # 初始时设为 left - 1，是因为左侧区间还没有开始增长，
        # 也就是说还没有任何元素被确认落在 pivot 左边。
        i = left - 1

        # 遍历当前区间中的所有元素，除了最后一个基准值 pivot 本身。
        # 变量 j 会从 left 遍历到 right - 1，也就是不包含最后一位 pivot。
        # 目的在于：把所有 <= pivot 的元素按顺序放到左半边，
        # 把所有 > pivot 的元素留在右半边。
        for j in range(left, right):
            # 如果当前元素 arr[j] 小于等于 pivot，说明它应该放在左侧。
            # 这样就满足“左边都 <= pivot，右边都 > pivot”的要求。
            if arr[j] <= pivot:
                # 让 i 右移一位，表示左侧有效区域要扩展一个位置。
                i += 1

                # 把当前元素 arr[j] 放到左侧区域的末尾位置 arr[i]。
                # 这一操作会把小于等于 pivot 的元素从原位置逐步前移，
                # 最终集中到左半部分。
                arr[i], arr[j] = arr[j], arr[i]

        # 现在所有小于等于 pivot 的元素已经在左侧，
        # 但 pivot 还在原来的右端点位置，因此需要把它放到最终位置。
        # 交换 pivot 和 arr[i + 1] 即可。
        arr[i + 1], arr[right] = arr[right], arr[i + 1]

        # pivot_index 表示基准元素最终落在哪个位置。
        pivot_index = i + 1

        # 对基准值左侧的子区间继续快速排序。
        _quick_sort(left, pivot_index - 1)

        # 对基准值右侧的子区间继续快速排序。
        _quick_sort(pivot_index + 1, right)

    # 从整个数组的 [0, len(arr)-1] 区间开始执行快速排序。
    _quick_sort(0, len(arr) - 1)

    # 返回排序后的新列表。
    return arr


# 这个判断保证：只有当文件被直接运行时，才执行下面的测试代码。
# 如果这个文件被当作模块导入，则不会自动执行测试，
# 这样可以避免在其他程序里不必要地跑测试。
if __name__ == "__main__":
    # 10 个测试用例，覆盖了多种常见情况：
    # 1. 普通无序数组
    # 2. 逆序数组
    # 3. 重复元素
    # 4. 空列表
    # 5. 单元素列表
    # 6. 负数
    # 7. 混合正负数
    # 8. 浮点数
    test_cases = [
        # 测试 1：基本升序排序
        ([3, 1, 2], [1, 2, 3]),

        # 测试 2：逆序数组
        ([5, 4, 3, 2, 1], [1, 2, 3, 4, 5]),

        # 测试 3：重复元素
        ([10, 10, 10, 10], [10, 10, 10, 10]),

        # 测试 4：空列表
        ([], []),

        # 测试 5：只有一个元素
        ([42], [42]),

        # 测试 6：混合正负数
        ([9, -3, 0, 5, -1], [-3, -1, 0, 5, 9]),

        # 测试 7：较长无序数组
        ([8, 1, 7, 2, 6, 3, 5, 4], [1, 2, 3, 4, 5, 6, 7, 8]),

        # 测试 8：重复元素且较复杂
        ([2, 1, 2, 1, 2], [1, 1, 2, 2, 2]),

        # 测试 9：浮点数排序
        ([3.5, 1.2, 2.7, 1.2, 9.9], [1.2, 1.2, 2.7, 3.5, 9.9]),

        # 测试 10：正负混合 + 非常规顺序
        ([7, 0, -5, 2, 9, 1, -2], [-5, -2, 0, 1, 2, 7, 9]),
    ]

    # passed 用来统计一共通过了多少条测试。
    passed = 0

    # enumerate(test_cases, start=1) 会给每个测试编号，
    # 从 1 开始递增，便于输出时定位第几条测试。
    for idx, (data, expected) in enumerate(test_cases, start=1):
        # 调用 quick_sort 对当前测试数据排序。
        result = quick_sort(data)

        # 判断排序结果是否与预期完全一致。
        ok = result == expected

        # 打印当前测试编号、排序结果和 PASS/FAIL 状态。
        print(f"Test {idx}: {result} -> {'PASS' if ok else 'FAIL'}")

        # 如果结果正确，就计数 +1。
        if ok:
            passed += 1

    # 输出最终总结果：多少条测试通过 / 一共多少条。
    print(f"\nTotal: {passed}/{len(test_cases)} passed")

